def build(project_root=None):
    """Return only the three owned tables; safe for targeted additive integration."""
    data = defaultdict(list)
    for variant, groups in (('extra', EXTRA), ('solo', SOLO)):
        for index, (title, lines) in enumerate(groups, 1):
            key = f'cafe.ambient.order.{variant}-{index:02}'
            data['OpeningPresentation'].append(dict(
                presentationId=key, titleKey=key + '.title',
                leftNameKey='player.name', rightNameKey='character.guest_a.name',
                visualsResource='Dialogue/CafeSceneVisuals'))
            data['Text'].append(dict(key=key + '.title', text=title, comment='Ordinary cafe order extension'))
            for seq, (speaker, body) in enumerate(lines, 1):
                text_key = f'{key}.text.{seq}'
                data['OpeningLine'].append(dict(
                    lineId=f'{key}.{seq}', presentationId=key, seq=seq,
                    speaker='right', gesture='none', textKey=text_key))
                data['Text'].append(dict(key=text_key, text=f'{speaker}：{body}',
                                         comment='Ordinary cafe order extension'))
    return dict(data)
